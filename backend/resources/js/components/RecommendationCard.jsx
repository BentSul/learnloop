import { PriorityBadge, StatusBadge } from './StatusBadge';

function formatLocalDateTime(isoString) {
    if (!isoString) return null;
    const d = new Date(isoString);
    if (Number.isNaN(d.getTime())) return isoString;
    return d.toLocaleString(undefined, {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
    });
}

/**
 * Displays one recommendation item (AGENTS.md §11) with state transition buttons:
 * - Active: Accept, Remind me later, Never again
 * - Accepted / Postponed: Never again
 * - Dismissed: Restore
 */
export default function RecommendationCard({
    rec,
    onAccept,
    onOpenPostpone,
    onDismiss,
    onRestore,
    onStartRevisionQuiz,
    busyId = null,
}) {
    const isBusy = busyId === rec.id;
    const perf = rec.performance;
    const hasPerfScore =
        perf && perf.performance_display !== null && perf.performance_display !== undefined;

    return (
        <article className="rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
            <div className="flex flex-wrap items-start justify-between gap-3">
                <div>
                    <div className="flex flex-wrap items-center gap-2">
                        <h2 className="text-base font-semibold text-slate-900">
                            {rec.topic?.name ?? `Topic #${rec.topic?.id}`}
                        </h2>
                        <PriorityBadge priority={rec.priority} />
                        {perf?.status && <StatusBadge status={perf.status} label={perf.label} />}
                        <span className="rounded-full bg-slate-100 px-2.5 py-0.5 text-xs capitalize text-slate-600">
                            {rec.state}
                        </span>
                    </div>
                    {hasPerfScore && (
                        <p className="mt-1 text-xs text-slate-500">
                            Score at recommendation: {perf.earned_marks}/{perf.max_marks} (
                            {perf.performance_display}%)
                        </p>
                    )}
                </div>

                {rec.reminder_at && (
                    <span className="rounded-md bg-amber-50 px-2.5 py-1 text-xs text-amber-800">
                        Reminder: {formatLocalDateTime(rec.reminder_at)}
                    </span>
                )}
            </div>

            {/* Reason sentences generated by backend */}
            {Array.isArray(rec.reasons) && rec.reasons.length > 0 && (
                <ul className="mt-3 space-y-1 text-sm text-slate-700">
                    {rec.reasons.map((sentence, idx) => (
                        <li key={idx} className="flex items-start gap-2">
                            <span className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-indigo-500" />
                            <span>{sentence}</span>
                        </li>
                    ))}
                </ul>
            )}

            {/* Suggested action banner */}
            {rec.suggested_action && (
                <div className="mt-3 flex flex-wrap items-center justify-between gap-2 rounded-lg bg-indigo-50/70 px-3.5 py-2.5 text-xs text-indigo-950">
                    <span>
                        <strong>Suggested next step:</strong> {rec.suggested_action.text}
                    </span>
                    {onStartRevisionQuiz &&
                        rec.topic?.id &&
                        ['revision_quiz', 'revise_topic', 'diagnostic'].includes(
                            rec.suggested_action.key,
                        ) && (
                            <button
                                type="button"
                                onClick={() => onStartRevisionQuiz(rec.topic.id)}
                                className="rounded-md bg-indigo-600 px-3 py-1 font-medium text-white hover:bg-indigo-700"
                            >
                                Start revision quiz
                            </button>
                        )}
                </div>
            )}

            {/* State transition actions */}
            <div className="mt-4 flex flex-wrap items-center gap-2 border-t border-slate-100 pt-3">
                {rec.state === 'active' && (
                    <>
                        {onAccept && (
                            <button
                                type="button"
                                disabled={isBusy}
                                onClick={() => onAccept(rec.id)}
                                className="rounded-md bg-emerald-700 px-3 py-1.5 text-xs font-medium text-white hover:bg-emerald-700 disabled:opacity-60"
                            >
                                Accept
                            </button>
                        )}
                        {onOpenPostpone && (
                            <button
                                type="button"
                                disabled={isBusy}
                                onClick={() => onOpenPostpone(rec)}
                                className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50 disabled:opacity-60"
                            >
                                Remind me later
                            </button>
                        )}
                        {onDismiss && (
                            <button
                                type="button"
                                disabled={isBusy}
                                onClick={() => onDismiss(rec.id)}
                                className="rounded-md border border-rose-200 bg-rose-50 px-3 py-1.5 text-xs font-medium text-rose-700 hover:bg-rose-100 disabled:opacity-60"
                            >
                                Never again
                            </button>
                        )}
                    </>
                )}

                {(rec.state === 'accepted' || rec.state === 'postponed') && onDismiss && (
                    <button
                        type="button"
                        disabled={isBusy}
                        onClick={() => onDismiss(rec.id)}
                        className="rounded-md border border-rose-200 bg-rose-50 px-3 py-1.5 text-xs font-medium text-rose-700 hover:bg-rose-100 disabled:opacity-60"
                    >
                        Never again
                    </button>
                )}

                {rec.state === 'dismissed' && onRestore && (
                    <button
                        type="button"
                        disabled={isBusy}
                        onClick={() => onRestore(rec.id)}
                        className="rounded-md border border-indigo-300 bg-indigo-50 px-3 py-1.5 text-xs font-medium text-indigo-700 hover:bg-indigo-100 disabled:opacity-60"
                    >
                        Restore recommendation
                    </button>
                )}
            </div>
        </article>
    );
}
